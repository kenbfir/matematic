export function getLandingVariant(page: LandingPageSlug, variant: Variant): LandingHeroContent {
  return LANDING_VARIANTS[page][variant] ?? LANDING_VARIANTS[page].a
}

export function isLandingPageSlug(value: string): value is LandingPageSlug {
  return (LANDING_PAGE_SLUGS as string[]).includes(value)
}
